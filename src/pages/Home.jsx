
import { useEffect, useRef, useState } from "react";
import {
  useLocation,
  useNavigate,
} from "react-router-dom";

import Navbar from "../components/Navbar/Navbar";
import DiagonalGallery from "../components/Gallery/DiagonalGallery";
import CDOpening from "../components/CDOpening/CDOpening";
import DarkProject from "../components/DarkProject/DarkProject";

import { projects } from "../data/projects";
import styles from "./Home.module.css";

/* =====================================
   HELPERS
===================================== */

const clamp = (value, min = 0, max = 1) =>
  Math.max(min, Math.min(max, value));

/* =====================================
   PROJECT DESTINATIONS
===================================== */

/*
  Every project has its own wrapper
  inside DarkProject.

  These IDs are generated by:

  id={`project-${record.slug}`}
*/

const PROJECT_TARGETS = {
  "het-mandje": "project-het-mandje",
  "animal-festival": "project-animal-festival",
  petbridge: "project-petbridge",
  bozar: "project-bozar",
  gistda: "project-gistda",
};

function getProjectTarget(project) {
  if (!project) return null;

  const slug = String(
    project.slug || project.title || ""
  ).toLowerCase();

  if (project.targetId) {
    const customTarget = document.getElementById(
      project.targetId
    );

    if (customTarget) {
      return customTarget;
    }
  }

  const targetId =
    PROJECT_TARGETS[slug] || `project-${slug}`;

  return document.getElementById(targetId);
}

/* =====================================
   SCROLL TO PROJECT
===================================== */

function scrollToProject(project) {
  const target = getProjectTarget(project);

  if (!target) return false;

  const targetY =
    window.scrollY +
    target.getBoundingClientRect().top;

  window.scrollTo({
    top: Math.max(0, targetY),
    behavior: "instant",
  });

  return true;
}

/* =====================================
   HOME COMPONENT
===================================== */

export default function Home() {
  const sectionRef = useRef(null);
  const navigationFrameRef = useRef(null);

  const [progress, setProgress] = useState(0);

  const location = useLocation();
  const navigate = useNavigate();

  /* =====================================
     SELECTED PROJECT FOR CD OPENING
  ===================================== */

  /*
    Het Mandje remains the default vinyl
    when visitors scroll normally.
  */

  const selectedProject =
    projects.find((project) =>
      String(project.slug || project.title)
        .toLowerCase()
        .includes("mandje")
    ) || projects[0];

  /* =====================================
     HOMEPAGE SCROLL PROGRESS
  ===================================== */

  useEffect(() => {
    let frame = null;

    function updateProgress() {
      frame = null;

      const section = sectionRef.current;

      if (!section) return;

      const rect = section.getBoundingClientRect();

      const scrollDistance =
        section.offsetHeight - window.innerHeight;

      if (scrollDistance <= 0) {
        setProgress(0);
        return;
      }

      setProgress(
        clamp(-rect.top / scrollDistance)
      );
    }

    function handleScroll() {
      if (frame !== null) return;

      frame = requestAnimationFrame(
        updateProgress
      );
    }

    updateProgress();

    window.addEventListener(
      "scroll",
      handleScroll,
      { passive: true }
    );

    window.addEventListener(
      "resize",
      handleScroll
    );

    return () => {
      window.removeEventListener(
        "scroll",
        handleScroll
      );

      window.removeEventListener(
        "resize",
        handleScroll
      );

      if (frame !== null) {
        cancelAnimationFrame(frame);
      }
    };
  }, []);

  /* =====================================
     OPEN PROJECT FROM HOMEPAGE GALLERY
  ===================================== */

  function handleProjectOpen(project) {
    // About Me has a separate experience.
    if (project?.slug === "about") {
      navigate("/about");
      return;
    }

    /*
      If the visitor clicked a CD on Home,
      there is no Projects origin to remember.

      Clear any previous returnTo state.
    */

    if (location.state?.returnTo) {
      navigate("/", {
        replace: true,
        state: null,
        preventScrollReset: true,
      });
    }

    const success = scrollToProject(project);

    if (!success) {
      console.warn(
        "Project section not found:",
        project?.slug
      );
    }
  }

  /* =====================================
     OPEN PROJECT FROM PROJECTS OVERVIEW
  ===================================== */

  /*
    ProjectsOverview sends:

    navigate("/", {
      state: {
        openProject: "petbridge",
        returnTo: "/projects"
      }
    });

    We scroll to the selected project,
    then remove only openProject.

    returnTo stays available for the
    X button in DarkProject.
  */

  useEffect(() => {
    const requestedSlug =
      location.state?.openProject ||
      (
        location.hash?.startsWith("#project-")
          ? location.hash.replace(
              /^#project-/,
              ""
            )
          : null
      );

    if (!requestedSlug) return;

    const requestedProject = projects.find(
      (project) =>
        project.slug === requestedSlug &&
        project.slug !== "about"
    );

    if (!requestedProject) return;

    let attempts = 0;
    let cancelled = false;

    function openRequestedProject() {
      if (cancelled) return;

      const target = getProjectTarget(
        requestedProject
      );

      if (!target) {
        if (attempts < 60) {
          attempts += 1;

          navigationFrameRef.current =
            requestAnimationFrame(
              openRequestedProject
            );
        } else {
          console.warn(
            "Requested project could not be found:",
            requestedSlug
          );
        }

        return;
      }

      /* Jump directly to the selected vinyl */

      const targetY =
        window.scrollY +
        target.getBoundingClientRect().top;

      window.scrollTo({
        top: Math.max(0, targetY),
        behavior: "instant",
      });

      /*
        IMPORTANT:
        Keep returnTo for the X button.

        Remove openProject so the user
        can scroll freely afterwards.
      */

      if (location.state?.openProject) {
        navigate(
          {
            pathname: "/",
            hash: "",
          },
          {
            replace: true,

            state: {
              returnTo:
                location.state?.returnTo ?? null,
            },

            preventScrollReset: true,
          }
        );
      }
    }

    navigationFrameRef.current =
      requestAnimationFrame(
        openRequestedProject
      );

    return () => {
      cancelled = true;

      if (navigationFrameRef.current !== null) {
        cancelAnimationFrame(
          navigationFrameRef.current
        );
      }
    };
  }, [
    location.state?.openProject,
    location.hash,
    navigate,
  ]);

  /* =====================================
     CD OPENING
  ===================================== */

  const departureProgress = clamp(
    (progress - 0.86) / 0.14
  );

  const openingInteractive =
    progress >= 0.82 &&
    progress < 0.86;

  const introOpacity = clamp(
    1 - progress / 0.15
  );

  /* =====================================
     RENDER
  ===================================== */

  return (
    <div className={styles.home}>

      {/* =====================================
          LIGHT HOME WORLD
      ===================================== */}

      <section
        ref={sectionRef}
        className={styles.scrollSection}
      >
        <div className={styles.stickyStage}>

          {/* NAVBAR */}

          <div className={styles.navigation}>
            <Navbar />
          </div>

          {/* INTRO */}

          <div
            className={styles.intro}
            style={{
              opacity: introOpacity,

              transform: `translateY(${
                -progress * 120
              }px)`,
            }}
          >
       

            <h1>
              Creative thinking.
              <br />
              Digital experiences.
            </h1>

            <p>
              A collection of my work in UX/UI,
              visual design and development.
            </p>
          </div>

          {/* =====================================
              INTERACTIVE PROJECT LIBRARY
          ===================================== */}

          <DiagonalGallery
            scrollProgress={progress}
            selectedProjectId={
              selectedProject.id
            }
            onProjectOpen={
              handleProjectOpen
            }
          />

          {/* =====================================
              OPENING JEWEL CASE
          ===================================== */}

          <div
            className={styles.cdOpeningLayer}
            style={{
              pointerEvents:
                openingInteractive
                  ? "auto"
                  : "none",
            }}
          >
            <CDOpening
              project={selectedProject}
              progress={progress}
              departureProgress={
                departureProgress
              }
            />
          </div>

          {/* SCROLL HINT */}

          <div
            className={styles.scrollHint}
            style={{
              opacity: clamp(
                1 - progress / 0.12
              ),
            }}
          >
            SCROLL TO EXPLORE
            <span>↓</span>
          </div>

        </div>
      </section>

      {/* =====================================
          DARK PROJECT EXPERIENCE
      ===================================== */}

      <DarkProject project={selectedProject} />

    </div>
  );
}
